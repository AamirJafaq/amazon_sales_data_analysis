/* Q.10 Calcualte the percentage of successful payments across all orders.
Challenge: Include breakdowns by payment status (e.g. failed, pending).
*/
-- Answer
SELECT count(o.order_id) AS total_orders, p.payment_status, 
		ROUND(100*count(o.order_id)::NUMERIC/(SELECT count(order_id) FROM payments), 2) AS percent
FROM orders AS o
JOIN payments AS p ON p.order_id=o.order_id
GROUP BY payment_status;


/* Q.11 Find the top 5 sellers based on total sales value.
Challenge: Include both successful and failed orders, and display their percentage of successful orders.
*/
-- Answer
WITH seller_sales AS (SELECT s.seller_id, s.seller_name, o.order_status,
			count(o.order_id) AS total_orders,ROUND(sum(oi.total_sales)::NUMERIC, 2) AS total_sales
FROM orders AS o
LEFT JOIN sellers AS s ON o.seller_id=s.seller_id
LEFT JOIN order_items AS oi ON oi.order_id=o.order_id
WHERE o.order_status IN ('Completed', 'Cancelled')
GROUP BY 1, 2,3
ORDER BY 1)
SELECT *, ROUND(100*total_orders/(SUM(total_orders) OVER (PARTITION BY seller_id)), 2) AS order_status_percentage
FROM seller_sales;

--or
WITH seller_sales AS (SELECT s.seller_id, s.seller_name, o.order_status, count(o.order_id) AS total_orders
FROM orders AS o
LEFT JOIN sellers AS s ON o.seller_id=s.seller_id
LEFT JOIN order_items AS oi ON oi.order_id=o.order_id
WHERE o.order_status IN ('Completed', 'Cancelled')
GROUP BY 1, 2, 3
ORDER BY 1)
SELECT seller_id, seller_name, 
 ROUND(sum(CASE WHEN order_status='Completed' THEN total_orders ELSE 0 END), 2) AS completed_orders,
 ROUND(sum(CASE WHEN order_status='Cancelled' THEN total_orders ELSE 0 END),2) AS cancelled_orders,
  sum(total_orders),
 ROUND(100*(sum(CASE WHEN order_status='Completed' THEN total_orders ELSE 0 END))/sum(total_orders),2) AS success_percent,
 ROUND(100*(sum(CASE WHEN order_status='Cancelled' THEN total_orders ELSE 0 END))/sum(total_orders),2) AS failed_percent
FROM seller_sales
GROUP BY 1, 2;


/* Q.12 Calculate the profit margin for each product (diff between price and cost of goods sold).
Challenge: Rank products by their margin, showing highest to lowest.
*/
-- Answer
SELECT p.product_id, ROUND(sum(p.cogs*oi.quantity)::NUMERIC,2) AS total_cost,  
			ROUND(sum(oi.total_sales)::NUMERIC,2) AS total_revenue,
			ROUND((sum(oi.total_sales)-sum(p.cogs*oi.quantity))::NUMERIC,2) AS profit,
		DENSE_RANK() OVER (ORDER BY (sum(oi.total_sales)-sum(p.cogs*oi.quantity)) DESC) AS ranking
FROM products AS p
RIGHT JOIN order_items AS oi ON p.product_id=oi.product_id
GROUP BY 1;


