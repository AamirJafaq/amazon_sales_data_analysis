/* Q.6 Identify the least selling product category for each state.
Challenge: Include the total sales for what category within each sate.
*/
-- Answer
SELECT category_id, category_name 
FROM category; 

WITH state_category_sales AS (SELECT c.state, cat.category_name, 
					sum(oi.total_sales)::NUMERIC AS total_sales, 
			RANK() OVER (PARTITION BY state ORDER BY sum(oi.total_sales) ASC) AS ranking
FROM order_items AS oi
JOIN orders AS o ON oi.order_id=o.order_id
JOIN products AS p ON p.product_id=oi.product_id
JOIN customers AS c ON c.customer_id=o.customer_id
JOIN category AS cat ON cat.category_id=p.category_id
GROUP BY 1, 2
ORDER BY c.state)
SELECT state, category_name, total_sales, ranking
FROM state_category_sales
WHERE ranking=1;


