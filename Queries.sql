/* Q.1 Query the top 10 products by total sales value.
Challenge: Include product name, total_quantity sold, and total sales value.
*/

-- First of all, we create a column for total sales as quantity*price_per_unit in order_items table.
ALTER TABLE order_items
ADD COLUMN total_sales FLOAT;

UPDATE order_items
SET total_sales=quantity*price_per_unit;

-- Answer
SELECT oi.product_id, p.product_name, sum(oi.quantity) AS total_quantity, 
		sum(oi.total_sales) AS total_sales
FROM orders AS o
LEFT JOIN order_items AS oi ON o.order_id=oi.order_id
LEFT JOIN products AS p ON p.product_id=oi.product_id 
GROUP BY 1, 2
ORDER BY total_sales DESC
LIMIT 10;

/* Q.2 Calculate total revenue generated by each product category.
Challenge: Include the percentage contribution of each category to total revenue.
*/
-- Answer
SELECT  p.category_id, c.category_name, sum(oi.total_sales) AS total_revenue, 
	100*sum(oi.total_sales)/(SELECT sum(total_sales) FROM order_items) AS percent_contribution
FROM order_items AS oi
LEFT JOIN products AS p ON p.product_id=oi.product_id
LEFT JOIN category AS c ON p.category_id= c.category_id
GROUP BY 1, 2
ORDER BY 1;


/* Q.3 Compute the average order value for each customer.
Challenge: Include only customers with more than 5 orders.
*/
-- Answer
SELECT c.customer_id, count(o.order_id) AS order_value, sum(oi.total_sales)
FROM customers AS c
JOIN orders AS o ON c.customer_id=o.customer_id
JOIN order_items AS oi ON oi.order_id=o.order_id
GROUP BY c.customer_id
HAVING count(o.order_id)>5
ORDER BY c.customer_id DESC;


/* Q.4 Montly Sales Trend
Query montly total sales over the past year.
Challenge; Display the sales trend, grouping by month, return current_month sale, last month sale.
*/
-- Answer
WITH last_year_sales AS (SELECT count(pay.order_id) AS total_orders, 
		EXTRACT(MONTH FROM payment_date) AS month, 
EXTRACT(YEAR FROM payment_date) AS YEAR, ROUND(sum(oi.total_sales)::NUMERIC, 2) AS total_sales
FROM payments AS pay
LEFT JOIN order_items AS oi ON pay.order_id=oi.order_id
WHERE pay.payment_status='Payment Successed' AND 
	payment_date >= (SELECT max(payment_date) FROM payments) - INTERVAL '1 YEAR'
GROUP BY 2, 3)
SELECT month, year, total_sales AS current_month_sales, 
		LAG(total_sales, 1) OVER (ORDER BY year DESC, month DESC) AS last_month_sales
FROM last_year_sales;

SELECT DISTINCT payment_status FROM payments;


